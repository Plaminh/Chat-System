[CmdletBinding()]
param(
    [string]$SchemaPath = (Join-Path $PSScriptRoot '..\schema.sql'),
    [string]$DbmlPath = (Join-Path $PSScriptRoot '..\..\docs\database\schema-v1.dbml')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

function Assert-True {
    param(
        [Parameter(Mandatory)]
        [bool]$Condition,
        [Parameter(Mandatory)]
        [string]$Message
    )

    if (-not $Condition) {
        throw "Schema validation failed: $Message"
    }
}

function Assert-Contains {
    param(
        [Parameter(Mandatory)]
        [string]$Content,
        [Parameter(Mandatory)]
        [string]$Token
    )

    Assert-True -Condition $Content.Contains($Token) -Message "missing required token '$Token'"
}

$resolvedSchemaPath = (Resolve-Path -LiteralPath $SchemaPath).Path
$resolvedDbmlPath = (Resolve-Path -LiteralPath $DbmlPath).Path
$schema = Get-Content -Raw -LiteralPath $resolvedSchemaPath
$dbml = Get-Content -Raw -LiteralPath $resolvedDbmlPath

$requiredTables = @(
    'users',
    'login_history',
    'friend_requests',
    'friendships',
    'user_blocks',
    'conversations',
    'direct_conversations',
    'conversation_members',
    'messages',
    'message_deletions',
    'spam_reports',
    'user_activity_logs'
)

$schemaTables = @(
    [regex]::Matches($schema, '(?im)^\s*CREATE TABLE\s+([a-z_]+)\s*\(') |
        ForEach-Object { $_.Groups[1].Value }
)
$dbmlTables = @(
    [regex]::Matches($dbml, '(?im)^\s*Table\s+([a-z_]+)\s*\{') |
        ForEach-Object { $_.Groups[1].Value }
)

Assert-True -Condition ($schemaTables.Count -eq 12) -Message "expected 12 schema tables, found $($schemaTables.Count)"
Assert-True -Condition ($dbmlTables.Count -eq 12) -Message "expected 12 DBML tables, found $($dbmlTables.Count)"

$schemaDifference = @(Compare-Object ($requiredTables | Sort-Object) ($schemaTables | Sort-Object))
$dbmlDifference = @(Compare-Object ($requiredTables | Sort-Object) ($dbmlTables | Sort-Object))
Assert-True -Condition ($schemaDifference.Count -eq 0) -Message 'schema table names differ from the approved contract'
Assert-True -Condition ($dbmlDifference.Count -eq 0) -Message 'DBML table names differ from the approved contract'

$requiredTokens = @(
    'GENERATED BY DEFAULT AS IDENTITY',
    'TIMESTAMPTZ',
    'uq_users_username_ci',
    'uq_users_email_ci',
    'uq_friend_requests_pending_pair',
    'chk_friendships_canonical_pair',
    'uq_friendships_pair',
    'uq_user_blocks_pair',
    'chk_conversations_shape',
    'uq_direct_conversations_pair',
    'history_cleared_at',
    'idx_messages_search',
    'unsent_at',
    'unsent_by',
    'uq_message_deletions_message_user',
    'chk_spam_reports_resolution_state',
    'idx_user_activity_logs_type_time',
    "activity_type IN ('app_open', 'direct_chat', 'group_chat')"
)

foreach ($token in $requiredTokens) {
    Assert-Contains -Content $schema -Token $token
}

$primaryKeyCount = ([regex]::Matches($schema, '(?i)\bPRIMARY KEY\b')).Count
$foreignKeyCount = ([regex]::Matches($schema, '(?i)\bFOREIGN KEY\b')).Count
$checkCount = ([regex]::Matches($schema, '(?i)\bCHECK\s*\(')).Count
$indexCount = ([regex]::Matches($schema, '(?im)^\s*CREATE (?:UNIQUE )?INDEX\s+')).Count

Assert-True -Condition ($primaryKeyCount -eq 12) -Message "expected 12 primary keys, found $primaryKeyCount"
Assert-True -Condition ($foreignKeyCount -ge 24) -Message "expected at least 24 foreign keys, found $foreignKeyCount"
Assert-True -Condition ($checkCount -ge 24) -Message "expected at least 24 check constraints, found $checkCount"
Assert-True -Condition ($indexCount -ge 30) -Message "expected at least 30 explicit indexes, found $indexCount"

Assert-True -Condition ($schema -notmatch '(?im)^\s*CREATE\s+(TRIGGER|FUNCTION|PROCEDURE)\b') -Message 'triggers, functions, and procedures are outside V1 scope'
Assert-True -Condition ($schema -notmatch '(?im)\bpassword\s+(VARCHAR|TEXT)\b') -Message 'plaintext password column detected'
Assert-True -Condition ($schema -notmatch '(?im)\b(friend_count|friends_count|app_open_count|chatted_users_count|chatted_groups_count)\b') -Message 'calculated counter column detected'

Write-Output 'Schema validation passed.'
Write-Output "Tables: $($schemaTables.Count)"
Write-Output "Primary keys: $primaryKeyCount"
Write-Output "Foreign keys: $foreignKeyCount"
Write-Output "Check constraints: $checkCount"
Write-Output "Explicit indexes: $indexCount"
