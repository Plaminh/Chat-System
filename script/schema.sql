-- Java Chat System - PostgreSQL Database V1
-- PostgreSQL 14+; apply with psql -X -v ON_ERROR_STOP=1.
-- This script intentionally fails when applied over an existing V1 schema.

SET client_encoding = 'UTF8';
SET TIME ZONE 'UTC';

-- Phase 02: users
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(10),
    role VARCHAR(10) NOT NULL DEFAULT 'user',
    account_status VARCHAR(10) NOT NULL DEFAULT 'active',
    locked_at TIMESTAMPTZ,
    password_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_username
        CHECK (username ~ '^[A-Za-z0-9_]{3,30}$'),
    CONSTRAINT chk_users_password_hash
        CHECK (length(btrim(password_hash)) >= 20),
    CONSTRAINT chk_users_email
        CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT chk_users_full_name
        CHECK (length(btrim(full_name)) BETWEEN 2 AND 100),
    CONSTRAINT chk_users_address
        CHECK (length(btrim(address)) > 0),
    CONSTRAINT chk_users_date_of_birth
        CHECK (date_of_birth < CURRENT_DATE),
    CONSTRAINT chk_users_gender
        CHECK (gender IS NULL OR gender IN ('male', 'female', 'other')),
    CONSTRAINT chk_users_role
        CHECK (role IN ('admin', 'user')),
    CONSTRAINT chk_users_account_status
        CHECK (account_status IN ('active', 'locked')),
    CONSTRAINT chk_users_lock_state
        CHECK (
            (account_status = 'active' AND locked_at IS NULL)
            OR (account_status = 'locked' AND locked_at IS NOT NULL)
        ),
    CONSTRAINT chk_users_timestamps
        CHECK (updated_at >= created_at AND password_changed_at >= created_at)
);

CREATE UNIQUE INDEX uq_users_username_ci ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email_ci ON users (lower(email));
CREATE INDEX idx_users_account_status ON users (account_status);
CREATE INDEX idx_users_created_at ON users (created_at DESC);
CREATE INDEX idx_users_full_name_ci ON users (lower(full_name));

-- Phase 03: login history
CREATE TABLE login_history (
    login_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    logged_in_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    logged_out_at TIMESTAMPTZ,
    CONSTRAINT fk_login_history_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_login_history_timestamps
        CHECK (logged_out_at IS NULL OR logged_out_at >= logged_in_at)
);

CREATE INDEX idx_login_history_user_time
    ON login_history (user_id, logged_in_at DESC);
CREATE INDEX idx_login_history_logged_in_at
    ON login_history (logged_in_at DESC);

-- Phase 04: friend requests
CREATE TABLE friend_requests (
    friend_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_user_id BIGINT NOT NULL,
    receiver_user_id BIGINT NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at TIMESTAMPTZ,
    CONSTRAINT fk_friend_requests_sender
        FOREIGN KEY (sender_user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_friend_requests_receiver
        FOREIGN KEY (receiver_user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_friend_requests_distinct_users
        CHECK (sender_user_id <> receiver_user_id),
    CONSTRAINT chk_friend_requests_status
        CHECK (status IN ('pending', 'accepted', 'declined', 'canceled')),
    CONSTRAINT chk_friend_requests_response_state
        CHECK (
            (status = 'pending' AND responded_at IS NULL)
            OR (status <> 'pending' AND responded_at IS NOT NULL)
        ),
    CONSTRAINT chk_friend_requests_timestamps
        CHECK (responded_at IS NULL OR responded_at >= created_at)
);

CREATE UNIQUE INDEX uq_friend_requests_pending_pair
    ON friend_requests (
        LEAST(sender_user_id, receiver_user_id),
        GREATEST(sender_user_id, receiver_user_id)
    )
    WHERE status = 'pending';
CREATE INDEX idx_friend_requests_receiver_status_time
    ON friend_requests (receiver_user_id, status, created_at DESC);
CREATE INDEX idx_friend_requests_sender_time
    ON friend_requests (sender_user_id, created_at DESC);

-- Phase 05: friendships and blocking
CREATE TABLE friendships (
    friendship_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low_id BIGINT NOT NULL,
    user_high_id BIGINT NOT NULL,
    established_by_request_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_friendships_user_low
        FOREIGN KEY (user_low_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_user_high
        FOREIGN KEY (user_high_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_request
        FOREIGN KEY (established_by_request_id)
        REFERENCES friend_requests (friend_request_id) ON DELETE SET NULL,
    CONSTRAINT chk_friendships_canonical_pair
        CHECK (user_low_id < user_high_id),
    CONSTRAINT uq_friendships_pair
        UNIQUE (user_low_id, user_high_id),
    CONSTRAINT uq_friendships_request
        UNIQUE (established_by_request_id)
);

CREATE INDEX idx_friendships_user_high ON friendships (user_high_id);
CREATE INDEX idx_friendships_created_at ON friendships (created_at DESC);

CREATE TABLE user_blocks (
    user_block_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_user_id BIGINT NOT NULL,
    blocked_user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_blocks_blocker
        FOREIGN KEY (blocker_user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_blocks_blocked
        FOREIGN KEY (blocked_user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_user_blocks_distinct_users
        CHECK (blocker_user_id <> blocked_user_id),
    CONSTRAINT uq_user_blocks_pair
        UNIQUE (blocker_user_id, blocked_user_id)
);

CREATE INDEX idx_user_blocks_blocked_user ON user_blocks (blocked_user_id);
CREATE INDEX idx_user_blocks_created_at ON user_blocks (created_at DESC);

-- Phase 06: conversations
CREATE TABLE conversations (
    conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_type VARCHAR(10) NOT NULL,
    name VARCHAR(100),
    owner_user_id BIGINT,
    encryption_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conversations_owner
        FOREIGN KEY (owner_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_conversations_type
        CHECK (conversation_type IN ('direct', 'group')),
    CONSTRAINT chk_conversations_shape
        CHECK (
            (conversation_type = 'direct' AND name IS NULL AND owner_user_id IS NULL)
            OR (
                conversation_type = 'group'
                AND name IS NOT NULL
                AND owner_user_id IS NOT NULL
                AND length(btrim(name)) BETWEEN 1 AND 100
            )
        ),
    CONSTRAINT chk_conversations_timestamps
        CHECK (updated_at >= created_at)
);

CREATE INDEX idx_conversations_type_created
    ON conversations (conversation_type, created_at DESC);
CREATE INDEX idx_conversations_group_name_ci
    ON conversations (lower(name))
    WHERE conversation_type = 'group';
CREATE INDEX idx_conversations_owner
    ON conversations (owner_user_id)
    WHERE owner_user_id IS NOT NULL;

-- Phase 07: direct conversation pairs and conversation membership
CREATE TABLE direct_conversations (
    conversation_id BIGINT PRIMARY KEY,
    user_low_id BIGINT NOT NULL,
    user_high_id BIGINT NOT NULL,
    CONSTRAINT fk_direct_conversations_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT fk_direct_conversations_user_low
        FOREIGN KEY (user_low_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_direct_conversations_user_high
        FOREIGN KEY (user_high_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_direct_conversations_canonical_pair
        CHECK (user_low_id < user_high_id),
    CONSTRAINT uq_direct_conversations_pair
        UNIQUE (user_low_id, user_high_id)
);

CREATE INDEX idx_direct_conversations_user_high
    ON direct_conversations (user_high_id);

CREATE TABLE conversation_members (
    conversation_member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    member_role VARCHAR(10) NOT NULL DEFAULT 'member',
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ,
    history_cleared_at TIMESTAMPTZ,
    CONSTRAINT fk_conversation_members_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT fk_conversation_members_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_conversation_members_role
        CHECK (member_role IN ('admin', 'member')),
    CONSTRAINT chk_conversation_members_timestamps
        CHECK (
            (left_at IS NULL OR left_at >= joined_at)
            AND (history_cleared_at IS NULL OR history_cleared_at >= joined_at)
            AND (
                left_at IS NULL
                OR history_cleared_at IS NULL
                OR history_cleared_at <= left_at
            )
        ),
    CONSTRAINT uq_conversation_members_pair
        UNIQUE (conversation_id, user_id)
);

CREATE INDEX idx_conversation_members_user_active
    ON conversation_members (user_id, joined_at DESC)
    WHERE left_at IS NULL;
CREATE INDEX idx_conversation_members_conversation_role_active
    ON conversation_members (conversation_id, member_role)
    WHERE left_at IS NULL;
CREATE INDEX idx_conversation_members_user_history
    ON conversation_members (user_id, left_at, joined_at DESC);

-- Phase 08: messages
CREATE TABLE messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_user_id BIGINT,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unsent_at TIMESTAMPTZ,
    unsent_by BIGINT,
    CONSTRAINT fk_messages_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT fk_messages_sender
        FOREIGN KEY (sender_user_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_messages_unsent_by
        FOREIGN KEY (unsent_by) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT chk_messages_body
        CHECK (length(btrim(body)) > 0),
    CONSTRAINT chk_messages_unsent_state
        CHECK (
            (unsent_at IS NULL AND unsent_by IS NULL)
            OR (unsent_at IS NOT NULL AND unsent_at >= created_at)
        )
);

CREATE INDEX idx_messages_conversation_time
    ON messages (conversation_id, created_at, message_id);
CREATE INDEX idx_messages_sender_time
    ON messages (sender_user_id, created_at DESC)
    WHERE sender_user_id IS NOT NULL;
CREATE INDEX idx_messages_search
    ON messages USING GIN (to_tsvector('simple', body));
