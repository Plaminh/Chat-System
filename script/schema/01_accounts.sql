-- Phase 02: users
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(10),
    role VARCHAR(10) NOT NULL DEFAULT 'user',
    account_status VARCHAR(10) NOT NULL DEFAULT 'active',
    locked_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    password_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_username
        CHECK (username ~ '^[A-Za-z0-9_]{3,30}$'),
    CONSTRAINT chk_users_password_hash
        CHECK (length(btrim(password_hash)) >= 20),
    CONSTRAINT chk_users_email
        CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT chk_users_full_name
        CHECK (length(btrim(full_name)) BETWEEN 2 AND 100),
    CONSTRAINT chk_users_address
        CHECK (length(btrim(address)) > 0),
    CONSTRAINT chk_users_date_of_birth
        CHECK (date_of_birth < CURRENT_DATE),
    CONSTRAINT chk_users_gender
        CHECK (gender IS NULL OR gender IN ('male', 'female', 'other')),
    CONSTRAINT chk_users_role
        CHECK (role IN ('admin', 'user')),
    CONSTRAINT chk_users_account_status
        CHECK (account_status IN ('active', 'locked', 'deleted')),
    CONSTRAINT chk_users_lock_state
        CHECK (
            (account_status = 'active' AND locked_at IS NULL AND deleted_at IS NULL)
            OR (account_status = 'locked' AND locked_at IS NOT NULL AND deleted_at IS NULL)
            OR (account_status = 'deleted' AND locked_at IS NULL AND deleted_at IS NOT NULL)
        ),
    CONSTRAINT chk_users_timestamps
        CHECK (updated_at >= created_at AND password_changed_at >= created_at)
);

CREATE UNIQUE INDEX uq_users_username_ci ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email_ci ON users (lower(email));
CREATE INDEX idx_users_account_status ON users (account_status);
CREATE INDEX idx_users_created_at ON users (created_at DESC);
CREATE INDEX idx_users_full_name_ci ON users (lower(full_name));

-- Versioned per-user public encryption keys for client-side encrypted groups.
-- Private keys remain on the User Client and are never stored by the server.
CREATE TABLE user_public_keys (
    user_public_key_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    key_version INTEGER NOT NULL,
    key_algorithm VARCHAR(40) NOT NULL DEFAULT 'DHKEM-X25519-HKDF-SHA256',
    public_key_format VARCHAR(20) NOT NULL DEFAULT 'RFC9180-RAW',
    public_key BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    retired_at TIMESTAMPTZ,
    CONSTRAINT fk_user_public_keys_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_user_public_keys_version
        CHECK (key_version > 0),
    CONSTRAINT chk_user_public_keys_algorithm
        CHECK (key_algorithm = 'DHKEM-X25519-HKDF-SHA256'),
    CONSTRAINT chk_user_public_keys_format
        CHECK (public_key_format = 'RFC9180-RAW'),
    CONSTRAINT chk_user_public_keys_material
        CHECK (octet_length(public_key) = 32),
    CONSTRAINT chk_user_public_keys_timestamps
        CHECK (retired_at IS NULL OR retired_at >= created_at),
    CONSTRAINT uq_user_public_keys_user_version
        UNIQUE (user_id, key_version)
);

CREATE UNIQUE INDEX uq_user_public_keys_active_user
    ON user_public_keys (user_id)
    WHERE retired_at IS NULL;
CREATE INDEX idx_user_public_keys_user_history
    ON user_public_keys (user_id, key_version DESC);

-- Phase 03: login history
CREATE TABLE login_history (
    login_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    logged_in_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    logged_out_at TIMESTAMPTZ,
    CONSTRAINT fk_login_history_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_login_history_timestamps
        CHECK (logged_out_at IS NULL OR logged_out_at >= logged_in_at)
);

CREATE INDEX idx_login_history_user_time
    ON login_history (user_id, logged_in_at DESC);
CREATE INDEX idx_login_history_logged_in_at
    ON login_history (logged_in_at DESC);
