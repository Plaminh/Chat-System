-- Phase 06: conversations
CREATE TABLE conversations (
    conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_type VARCHAR(10) NOT NULL,
    name VARCHAR(100),
    owner_user_id BIGINT,
    encryption_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conversations_owner
        FOREIGN KEY (owner_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_conversations_type
        CHECK (conversation_type IN ('direct', 'group')),
    CONSTRAINT chk_conversations_shape
        CHECK (
            (conversation_type = 'direct' AND name IS NULL AND owner_user_id IS NULL)
            OR (
                conversation_type = 'group'
                AND name IS NOT NULL
                AND owner_user_id IS NOT NULL
                AND length(btrim(name)) BETWEEN 1 AND 100
            )
        ),
    CONSTRAINT chk_conversations_timestamps
        CHECK (updated_at >= created_at),
    CONSTRAINT chk_conversations_encryption_scope
        CHECK (conversation_type = 'group' OR NOT encryption_enabled),
    CONSTRAINT uq_conversations_id_encryption
        UNIQUE (conversation_id, encryption_enabled)
);

CREATE INDEX idx_conversations_type_created
    ON conversations (conversation_type, created_at DESC);
CREATE INDEX idx_conversations_group_name_ci
    ON conversations (lower(name))
    WHERE conversation_type = 'group';
CREATE INDEX idx_conversations_owner
    ON conversations (owner_user_id)
    WHERE owner_user_id IS NOT NULL;

-- Phase 07: direct conversation pairs and conversation membership
CREATE TABLE direct_conversations (
    conversation_id BIGINT PRIMARY KEY,
    user_low_id BIGINT NOT NULL,
    user_high_id BIGINT NOT NULL,
    CONSTRAINT fk_direct_conversations_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT fk_direct_conversations_user_low
        FOREIGN KEY (user_low_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_direct_conversations_user_high
        FOREIGN KEY (user_high_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_direct_conversations_canonical_pair
        CHECK (user_low_id < user_high_id),
    CONSTRAINT uq_direct_conversations_pair
        UNIQUE (user_low_id, user_high_id)
);

CREATE INDEX idx_direct_conversations_user_high
    ON direct_conversations (user_high_id);

CREATE TABLE conversation_members (
    conversation_member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    member_role VARCHAR(10) NOT NULL DEFAULT 'member',
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ,
    history_cleared_at TIMESTAMPTZ,
    CONSTRAINT fk_conversation_members_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT fk_conversation_members_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_conversation_members_role
        CHECK (member_role IN ('admin', 'member')),
    CONSTRAINT chk_conversation_members_timestamps
        CHECK (
            (left_at IS NULL OR left_at >= joined_at)
            AND (history_cleared_at IS NULL OR history_cleared_at >= joined_at)
            AND (
                left_at IS NULL
                OR history_cleared_at IS NULL
                OR history_cleared_at <= left_at
            )
        ),
    CONSTRAINT uq_conversation_members_pair
        UNIQUE (conversation_id, user_id)
);

CREATE INDEX idx_conversation_members_user_active
    ON conversation_members (user_id, joined_at DESC)
    WHERE left_at IS NULL;
CREATE INDEX idx_conversation_members_conversation_role_active
    ON conversation_members (conversation_id, member_role)
    WHERE left_at IS NULL;
CREATE INDEX idx_conversation_members_user_history
    ON conversation_members (user_id, left_at, joined_at DESC);

-- Client-generated group-key epochs. Group-key material is stored only in the
-- recipient-specific encrypted envelopes below; the server has no decryption key.
CREATE TABLE conversation_key_versions (
    conversation_key_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    key_version INTEGER NOT NULL,
    encryption_algorithm VARCHAR(30) NOT NULL DEFAULT 'AES-256-GCM',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    retired_at TIMESTAMPTZ,
    CONSTRAINT fk_conversation_key_versions_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT chk_conversation_key_versions_version
        CHECK (key_version > 0),
    CONSTRAINT chk_conversation_key_versions_algorithm
        CHECK (encryption_algorithm = 'AES-256-GCM'),
    CONSTRAINT chk_conversation_key_versions_timestamps
        CHECK (retired_at IS NULL OR retired_at >= created_at),
    CONSTRAINT uq_conversation_key_versions_conversation_version
        UNIQUE (conversation_id, key_version)
);

CREATE INDEX idx_conversation_key_versions_active
    ON conversation_key_versions (conversation_id, key_version DESC)
    WHERE retired_at IS NULL;

-- One RFC 9180 HPKE base-mode envelope per recipient public key and group-key epoch.
-- Profile: KEM 0x0020, KDF 0x0001, AEAD 0x0002; info is the UTF-8 string
-- "JavaChatSystem-V1-GroupKey". AAD is the canonical UTF-8 context documented in the
-- schema contract, derived from conversation/epoch/recipient identities. encrypted_group_key
-- is Seal() output for a 32-byte group key and includes the AEAD tag.
CREATE TABLE conversation_key_envelopes (
    conversation_key_envelope_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_key_version_id BIGINT NOT NULL,
    recipient_public_key_id BIGINT NOT NULL,
    envelope_algorithm VARCHAR(64) NOT NULL
        DEFAULT 'HPKE-BASE-X25519-HKDF-SHA256-AES-256-GCM',
    encapsulated_key BYTEA NOT NULL,
    encrypted_group_key BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_conversation_key_envelopes_version
        FOREIGN KEY (conversation_key_version_id)
        REFERENCES conversation_key_versions (conversation_key_version_id) ON DELETE CASCADE,
    CONSTRAINT fk_conversation_key_envelopes_recipient_key
        FOREIGN KEY (recipient_public_key_id)
        REFERENCES user_public_keys (user_public_key_id) ON DELETE RESTRICT,
    CONSTRAINT chk_conversation_key_envelopes_algorithm
        CHECK (envelope_algorithm = 'HPKE-BASE-X25519-HKDF-SHA256-AES-256-GCM'),
    CONSTRAINT chk_conversation_key_envelopes_encapsulated_key
        CHECK (octet_length(encapsulated_key) = 32),
    CONSTRAINT chk_conversation_key_envelopes_ciphertext
        CHECK (octet_length(encrypted_group_key) = 48),
    CONSTRAINT uq_conversation_key_envelopes_version_recipient
        UNIQUE (conversation_key_version_id, recipient_public_key_id)
);

CREATE INDEX idx_conversation_key_envelopes_recipient
    ON conversation_key_envelopes (recipient_public_key_id, conversation_key_version_id);
