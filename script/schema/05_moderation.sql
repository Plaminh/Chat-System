-- Phase 10: spam reports
CREATE TABLE spam_reports (
    spam_report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id BIGINT,
    reported_user_id BIGINT,
    message_id BIGINT,
    reason TEXT NOT NULL,
    review_status VARCHAR(12) NOT NULL DEFAULT 'pending',
    reviewed_by BIGINT,
    resolution_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT fk_spam_reports_reporter
        FOREIGN KEY (reporter_user_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_spam_reports_reported_user
        FOREIGN KEY (reported_user_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_spam_reports_message
        FOREIGN KEY (message_id) REFERENCES messages (message_id) ON DELETE SET NULL,
    CONSTRAINT fk_spam_reports_reviewer
        FOREIGN KEY (reviewed_by) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT chk_spam_reports_distinct_users
        CHECK (
            reporter_user_id IS NULL
            OR reported_user_id IS NULL
            OR reporter_user_id <> reported_user_id
        ),
    CONSTRAINT chk_spam_reports_reason
        CHECK (length(btrim(reason)) > 0),
    CONSTRAINT chk_spam_reports_status
        CHECK (review_status IN ('pending', 'reviewing', 'resolved', 'dismissed')),
    CONSTRAINT chk_spam_reports_resolution_state
        CHECK (
            (review_status IN ('pending', 'reviewing') AND resolved_at IS NULL)
            OR (review_status IN ('resolved', 'dismissed') AND resolved_at IS NOT NULL)
        ),
    CONSTRAINT chk_spam_reports_resolution_note
        CHECK (resolution_note IS NULL OR length(btrim(resolution_note)) > 0),
    CONSTRAINT chk_spam_reports_timestamps
        CHECK (resolved_at IS NULL OR resolved_at >= created_at)
);

CREATE INDEX idx_spam_reports_status_time
    ON spam_reports (review_status, created_at DESC);
CREATE INDEX idx_spam_reports_reported_user_time
    ON spam_reports (reported_user_id, created_at DESC)
    WHERE reported_user_id IS NOT NULL;
CREATE INDEX idx_spam_reports_reporter_time
    ON spam_reports (reporter_user_id, created_at DESC)
    WHERE reporter_user_id IS NOT NULL;
CREATE INDEX idx_spam_reports_reviewer
    ON spam_reports (reviewed_by)
    WHERE reviewed_by IS NOT NULL;
CREATE INDEX idx_spam_reports_message
    ON spam_reports (message_id)
    WHERE message_id IS NOT NULL;
